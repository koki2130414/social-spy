-- ---------------------------------------------------------------------------
-- SPY MISSION を全員に公開するかどうかの設定
--
-- これまでは「SPY MISSION公開」のフェーズへ進めば、必ず全員が
-- SPY MISSION の内容を読める作りだった。
--
-- 会によっては、最後までヒントを出さずに探してもらいたいことがある。
-- そこで、イベントごとに公開する・しないを選べるようにする。
--
-- 既定は true（これまでと同じ動き）。false にすると、フェーズが進んでも
-- SPY本人以外には内容を出さない。画面で隠すのではなく、
-- サーバーが応答に含めないので、通信を覗いても読めない。
--
-- 何度実行しても同じ結果になります。
-- ---------------------------------------------------------------------------

alter table public.events
  add column if not exists spy_mission_public boolean not null default true;

comment on column public.events.spy_mission_public is
  'SPY MISSION の内容を全員に見せるか。false なら公開のフェーズでもSPY本人だけが見られる。';

-- ---------------------------------------------------------------------------
-- 確認
-- ---------------------------------------------------------------------------
select code, name, phase, spy_mission_public
  from public.events
 order by created_at;
