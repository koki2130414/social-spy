-- ---------------------------------------------------------------------------
-- イベントを「しまっておく」ための印
--
-- 終わったイベントが一覧に並び続けると、当日ぜったいに選び間違える。
-- かといって消してしまうと、達成率や投票の記録まで一緒に消えてしまう。
-- そこで、消さずにしまう（アーカイブ）を用意する。
--
-- 本当に消すのは、投票がまだ1件も無いイベントだけにしている。
-- 投票が入ったイベントを消そうとすると votes の削除禁止トリガに当たり、
-- 途中まで消えた状態で失敗する。サービス側でも同じ条件を確かめている。
--
-- 何度実行しても同じ結果になります。
-- ---------------------------------------------------------------------------

alter table public.events
  add column if not exists archived_at timestamptz;

comment on column public.events.archived_at is
  'しまってある日時。null なら現役。参加者向けの画面には影響しない（運営の一覧の並びだけが変わる）。';

-- しまっていないイベントを引く問い合わせを速くする
create index if not exists events_archived_idx on public.events (archived_at);

-- ---------------------------------------------------------------------------
-- 確認
-- ---------------------------------------------------------------------------
select code, name, archived_at
  from public.events
 order by created_at;
