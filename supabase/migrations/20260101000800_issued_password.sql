-- ---------------------------------------------------------------------------
-- 運営画面で参加者のパスワードを見えるようにする
--
-- これまでパスワードはハッシュだけを保存していた。安全な作りだが、
-- 当日「紙をなくした」「パスワードを忘れた」と言われたときに
-- 運営が答えられず、毎回作り直すしかなかった。作り直すと配ったカードの
-- パスワードが使えなくなるので、受付が余計に混乱する。
--
-- そこで、発行した数字4桁をそのまま保存して運営画面に出せるようにする。
--
-- --- なぜ平文で持ってよいと判断したか ---
--
--  ・この値は本人が決めたパスワードではなく、アプリが自動発行した
--    その日かぎりの数字4桁。他のサービスで使い回されることがない。
--  ・同じ内容の一覧を、すでに紙（受付カード・受付一覧）として
--    運営が持っている。アプリに持たせても新しく増える危険がない。
--  ・イベント終了後は不要になる。
--
-- --- それでも守ること ---
--
--  ・参加者向けのAPIには絶対に含めない（他人のパスワードが見えてしまう）。
--  ・運営メンバーのログインパスワードは、これまでどおりハッシュのみ。
--    こちらは本人が決めるもので、使い回されうるため平文にしてはならない。
--  ・RLS により anon からは participants を一切読めない（既存の設定のまま）。
--  ・照合は今までどおりハッシュで行う。この列は表示専用。
--
-- 何度実行しても同じ結果になるよう書いてある。
-- ---------------------------------------------------------------------------

alter table public.participants
  add column if not exists issued_password text;

comment on column public.participants.issued_password is
  '運営が受付で伝えるために保存している、自動発行の数字4桁。表示専用でログイン照合には使わない。参加者向けAPIへ含めないこと。';
